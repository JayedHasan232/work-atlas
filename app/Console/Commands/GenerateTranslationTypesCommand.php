<?php

namespace App\Console\Commands;

use App\Support\Localization\TranslationFiles;
use Illuminate\Console\Command;
use Illuminate\Support\Facades\Config;
use Illuminate\Support\Facades\File;

/**
 * Writes the TypeScript type of every translation key React can use, so `t()` rejects unknown keys
 * at compile time. The Vite build runs this; the output is not committed.
 */
final class GenerateTranslationTypesCommand extends Command
{
    protected $signature = 'atlas:translation-types
        {--path=resources/js/types/translation-keys.generated.ts : Output file, relative to the project root}';

    protected $description = 'Generate the TypeScript type of the translation keys shared with React';

    public function handle(): int
    {
        /** @var list<string> $groups */
        $groups = Config::array('atlas.translations.always');

        /** @var array<string, list<string>> $pages */
        $pages = Config::array('atlas.translations.pages');

        foreach ($pages as $pageGroups) {
            $groups = [...$groups, ...$pageGroups];
        }

        $groups = array_unique($groups);
        $strings = (new TranslationFiles(lang_path()))->strings(Config::string('app.fallback_locale'));

        $keys = array_filter(
            array_keys($strings),
            fn (string $key): bool => in_array(strtok($key, '.'), $groups, true),
        );

        $lines = array_map(fn (string $key): string => '    | '.json_encode($key, JSON_UNESCAPED_UNICODE), $keys);

        $contents = "// Generated by `php artisan atlas:translation-types` from lang/en. Do not edit:\n"
            ."// `npm run build` or `npm run dev` regenerates it.\n"
            ."export type TranslationKey =\n"
            .($lines === [] ? '    never' : implode("\n", $lines)).";\n";

        $path = base_path($this->stringOption('path'));

        if (! File::exists($path) || File::get($path) !== $contents) {
            File::put($path, $contents);
        }

        return self::SUCCESS;
    }

    private function stringOption(string $name): string
    {
        $value = $this->option($name);

        return is_string($value) ? $value : '';
    }
}
